function [S, common, d] = cosineSimilarity(B)
    N      = size(B, 1);
    d      = full(sum(B, 2));
    Bn     = spdiags(1 ./ sqrt(d), 0, N, N) * B;
    S      = full(Bn * Bn');
    common = full(B * B');
end


